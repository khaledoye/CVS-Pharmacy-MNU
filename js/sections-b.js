    m.appendChild(U.kp(['Class I = Na⁺ (phase 0, conduction). IA moderate +↑APD, IB weak +↓APD, IC strong, APD unchanged.', 'Class II = β-blockade: nodal phase 4 and AV conduction.', 'Class III = K⁺ (phase 3): ↑APD and ERP — and ↑QT.', 'Class IV = Ca²⁺: the SA and AV nodes only.', 'Sotalol and amiodarone belong to more than one class — which is why they also slow the heart rate.']));
