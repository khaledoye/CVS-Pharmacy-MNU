  /* ---------------- 7. DRUG → ACTION POTENTIAL ---------------- */
  S.drugap = function (m, sub) {
    m.appendChild(U.chain(5));
    let sel = [sub && K.drugs[sub] ? sub : 'procainamide'];
    let tissue = 'fast', isch = false;
    const card = U.card('Drug → action potential simulator');
    const picker = h('div', { class: 'picker' });
    K.drugOrder.forEach((d) => picker.appendChild(h('button', { class: 'pbtn', 'data-d': d, onclick: () => toggle(d) }, K.drugs[d].name, h('i', {}, K.drugs[d].cls))));
    const tSeg = U.seg([['fast', 'Ventricular myocyte'], ['purkinje', 'Purkinje fibre'], ['node', 'SA / AV nodal cell']], 'fast', (t) => { tissue = t; draw(); });
    const plotHost = h('div', {}), metHost = h('div', { class: 'metrics' }), infoHost = h('div', {});
    card.appendChild(picker); card.appendChild(h('div', { class: 'row' }, tSeg, U.toggle('Ischaemic / depolarised tissue', false, (b) => { isch = b; draw(); })));
    card.appendChild(plotHost); card.appendChild(metHost); card.appendChild(infoHost);
    m.appendChild(card);
    const AP = new RD.APPlot(plotHost, { h: 300, yr: [-100, 50], xr: [0, 520] });

    function toggle(d) {
      const i = sel.indexOf(d);
      if (i >= 0) { if (sel.length > 1) sel.splice(i, 1); }
      else { if (sel.length >= 3) sel.shift(); sel.push(d); }
      draw();
    }
    const COLS = ['#5eead4', '#fbbf24', '#f472b6'];
    function fx(d) {
      const dr = K.drugs[d];
      if (d === 'lidocaine' && isch && dr.fxIsch) return dr.fxIsch;
      return dr.fx;
    }
    function draw() {
      picker.querySelectorAll('.pbtn').forEach((b) => b.classList.toggle('on', sel.includes(b.dataset.d)));
      AP.series = []; AP.phases = null;
      const node = tissue === 'node';
      AP.yr = node ? [-80, 30] : [-100, 50]; AP.xr = node ? [0, 2400] : [0, 520];
      AP.title = node ? 'Slow-response (nodal) action potential' : tissue === 'purkinje' ? 'Purkinje fibre (fast response)' : 'Ventricular myocyte (fast response)';
      const opt = { purkinje: tissue === 'purkinje', T: node ? 2400 : 520 };
      const norm = node ? EP.nodeAP(EP.BASE, opt) : EP.fastAP(EP.BASE, opt);
      AP.series.push({ t: norm.t, v: norm.v, color: 'rgba(148,163,184,0.55)', dash: [5, 4], w: 1.6, label: 'No drug' });
      const rows = [];
      sel.forEach((d, i) => {
        const P = EP.combine([fx(d)]);
        const ap = node ? EP.nodeAP(P, opt) : EP.fastAP(P, opt);
        AP.series.push({ t: ap.t, v: ap.v, color: COLS[i], w: 2.3, label: K.drugs[d].name });
        if (!node) AP.phases = ap.phases;
        const iv = EP.intervals(P);
        rows.push([K.drugs[d].name, K.drugs[d].cls,
          node ? '—' : pc(ap.dvdt, norm.dvdt), node ? '—' : pc(ap.apd90, norm.apd90), node ? '—' : pc(ap.erp, norm.erp),
          node ? pc(ap.hr, norm.hr) : '—', node ? pc(ap.avTime, norm.avTime) : '—', node ? pc(ap.avERP, norm.avERP) : '—']);
      });
      AP.draw();
      metHost.innerHTML = '';
      metHost.appendChild(U.table(['Drug', 'Class', 'dV/dt (phase 0)', 'APD90', 'ERP', 'Nodal rate', 'AV conduction time', 'AV-nodal ERP'], rows, 'cmp-t'));
      metHost.appendChild(U.note('M', 'Percentages are the model’s output relative to no drug. They show the direction and the relative size of each effect, not a clinical prediction. The model has no drug concentrations: each drug is one fixed “therapeutic” point.'));
      infoHost.innerHTML = '';
      sel.forEach((d, i) => infoHost.appendChild(profile(d, COLS[i])));
    }
    function pc(v, n) {
      if (!isFinite(v) || !isFinite(n)) return 'block';
      const r = v / n; const s = ((r - 1) * 100);
      if (Math.abs(s) < 1.5) return h('span', { class: 'dz' }, '≈ unchanged');
      return h('span', { class: s > 0 ? 'up' : 'dn' }, (s > 0 ? '▲ +' : '▼ ') + s.toFixed(0) + '%');
    }
    function profile(d, col) {
      const dr = K.drugs[d];
      const box = h('div', { class: 'profile' });
      box.appendChild(h('h4', { style: { borderColor: col } }, dr.name, ' ', h('span', { class: 'gchip' }, dr.label)));
      box.appendChild(U.dl([
        ['Molecular target', dr.target], ['Receptor / channel type', dr.receptor],
        ['Mechanism (lecture)', [dr.mech.L, ' ', U.tag('L')]],
        ['Mechanism (supplementary)', [dr.mech.S, ' ', U.tag('S')]],
        ['Action potential phase affected', dr.phase],
        ['Conduction velocity', dr.cv], ['APD', dr.apd], ['ERP', dr.erp],
        ['Expected ECG change', dr.ecg]]));
      box.appendChild(h('div', { class: 'two' },
        h('div', {}, U.sub('Therapeutic uses'), h('ul', {}, dr.uses.map((x) => h('li', {}, x)))),
        h('div', {}, U.sub('Adverse effects'), h('ul', {}, dr.adverse.map((x) => h('li', {}, x))))));
      box.appendChild(U.sub('Precautions and contraindications'));
      box.appendChild(h('ul', { class: 'prec' }, dr.prec.map((x) => h('li', {}, x))));
      if (dr.acute) box.appendChild(U.note('U', dr.acute));
      box.appendChild(U.note('S', dr.clinical));
      box.appendChild(h('div', { class: 'row' }, U.link('drugecg', d, 'See its ECG effect'), U.link('classes', null, 'Its class')));
      return box;
    }
    draw();
    card.appendChild(U.note('S', 'Pick up to three drugs to overlay. Switch tissue to see the central point of this module: the same drug does completely different things in different tissues. Verapamil barely touches the ventricular action potential but transforms the nodal one; lidocaine does almost nothing to normal tissue until you make it ischaemic.'));

    const c = U.checks('drugap'); if (c) m.appendChild(c);
    m.appendChild(U.kp(['Always ask which tissue: fast-response (Na⁺-driven) or nodal (Ca²⁺-driven).', 'IA ↓phase 0 and ↑APD/ERP; IB ↓APD/ERP with little effect on normal conduction; IC ↓↓phase 0 with APD unchanged.', 'Class III widens phase 3 — the APD and ERP rise together and so does the QT.', 'Class II and IV act on the nodes: rate and AV conduction, not QRS width.']));
  };

  /* ---------------- 8. DRUG → ECG ---------------- */
  S.drugecg = function (m, sub) {
    m.appendChild(U.chain(3));
    let base = 'nsr', drug = 'none', Ko = 4;
    const card = U.card('Drug → ECG simulator');
    const baseSeg = U.seg([['nsr', 'Normal sinus rhythm'], ['af', 'Atrial fibrillation'], ['preaf', 'Pre-excited AF (WPW)'], ['vt', 'Ventricular tachycardia']], 'nsr', (b) => { base = b; draw(); });
    const picker = h('div', { class: 'picker' });
    picker.appendChild(h('button', { class: 'pbtn on', 'data-d': 'none', onclick: () => { drug = 'none'; draw(); } }, 'No drug'));
    K.drugOrder.forEach((d) => picker.appendChild(h('button', { class: 'pbtn', 'data-d': d, onclick: () => { drug = d; draw(); } }, K.drugs[d].name)));
    const before = h('div', {}), after = h('div', {}), tbl = h('div', {}), expl = h('div', {});
    card.appendChild(baseSeg); card.appendChild(picker);
    card.appendChild(U.slider('Extracellular K⁺ [K⁺]o', 2.2, 6, 0.1, 4, (v) => { Ko = v; draw(); }, (v) => v.toFixed(1) + ' mM'));
    card.appendChild(h('div', { class: 'two' }, h('div', {}, U.sub('Before — no drug'), before), h('div', {}, U.sub('After'), after)));
    card.appendChild(tbl); card.appendChild(expl);
    m.appendChild(card);

    function strip(host, P, label, seed) {
      host.innerHTML = '';
      const iv = EP.intervals(P, { Ko });
      let gen;
      if (base === 'nsr') gen = () => EP.rhythms.nsr({ hr: iv.hr, pr: Math.min(iv.pr, 420), qrs: iv.qrs, qt: iv.qt, dur: 6000, extra: drug === 'digoxin' ? { dig: true } : null });
      else if (base === 'af') gen = (s) => EP.rhythms.af({ seed: s, dur: 6000, avERP: iv.avERP, qrs: iv.qrs });
      else if (base === 'preaf') gen = (s) => EP.rhythms.af({ seed: s, dur: 6000, avERP: iv.avERP, apERP: EP.apERP(P).erp });
      else gen = () => EP.rhythms.vt({ dur: 6000, hr: 180 });
      const st = new RD.ECGStrip(host, { gen, dur: 6000, ecgH: 150, label });
      if (base === 'af' || base === 'preaf') { st.regen = true; st.rh.ladderAF = true; }
      return iv;
    }
    function draw() {
      picker.querySelectorAll('.pbtn').forEach((b) => b.classList.toggle('on', b.dataset.d === drug));
      const P0 = EP.clone(EP.BASE), P1 = drug === 'none' ? EP.clone(EP.BASE) : EP.combine([K.drugs[drug].fx]);
      const i0 = strip(before, P0, 'No drug', 1);
      const i1 = strip(after, P1, drug === 'none' ? 'No drug' : K.drugs[drug].name, 1);
      const rate = (iv) => {
        if (base === 'af' || base === 'preaf') { const r = EP.rhythms.af({ seed: 11, dur: 60000, avERP: iv.avERP, apERP: base === 'preaf' ? EP.apERP(drug === 'none' ? EP.BASE : EP.combine([K.drugs[drug].fx])).erp : null }); return r.beats.length; }
        return base === 'vt' ? 180 : iv.hr;
      };
      tbl.innerHTML = '';
      const rows = [
        ['Heart rate / ventricular rate', Math.round(rate(i0)) + ' /min', Math.round(rate(i1)) + ' /min'],
        ['PR interval', base === 'nsr' ? fmt(i0.pr) : '—', base === 'nsr' ? fmt(i1.pr) : '—'],
        ['QRS duration', fmt(i0.qrs), fmt(i1.qrs)],
        ['QT interval', fmt(i0.qt), fmt(i1.qt)],
        ['QTc (Bazett)', fmt(i0.qtc), fmt(i1.qtc)],
        ['AV-nodal ERP', fmt(i0.avERP), fmt(i1.avERP)],
        ['Ventricular APD90', fmt(i0.fast.apd90), fmt(i1.fast.apd90)],
        ['Ventricular ERP', fmt(i0.fast.erp), fmt(i1.fast.erp)]
      ];
      if (base === 'preaf') rows.push(['Accessory-pathway ERP', fmt(EP.apERP(P0).erp), fmt(EP.apERP(P1).erp)]);
      tbl.appendChild(U.table(['Measurement', 'Before', 'After'], rows, 'cmp-t'));
      expl.innerHTML = '';
      if (drug !== 'none') {
        const dr = K.drugs[drug];
        expl.appendChild(h('h4', {}, dr.name, ' — expected ECG effect'));
        expl.appendChild(h('p', {}, dr.ecg, ' ', U.tag('L')));
        expl.appendChild(h('p', {}, h('b', {}, 'Why: '), dr.mech.S));
        if (dr.acute) expl.appendChild(U.note('U', dr.acute));
      }
      // context warnings — the clinically important ones
      const W = [];
      if (base === 'vt' && (drug === 'verapamil' || drug === 'diltiazem')) W.push(['danger', 'IV verapamil should never be used in VT → haemodynamic collapse (lecture). VT does not use the AV node, so the drug cannot terminate it, while its vasodilator and negative inotropic effects destroy an already compromised output. The trace above is unchanged for exactly that reason.']);
      if (base === 'vt' && drug === 'adenosine') W.push(['danger', 'Adenosine acts on the AV node, which is not part of a ventricular re-entry circuit — it will not terminate VT.']);
      if (base === 'preaf' && ['verapamil', 'diltiazem', 'digoxin', 'metoprolol', 'adenosine'].includes(drug)) W.push(['danger', 'AV-nodal blocker in pre-excited AF. The lecture says to avoid adenosine here; the same logic applies to verapamil, diltiazem, digoxin and β-blockers. Blocking the node does nothing to the accessory pathway — and removes the competition, so MORE impulses take the pathway. The ventricular rate can accelerate to the point of ventricular fibrillation.']);
      if (base === 'preaf' && drug === 'procainamide') W.push(['good', 'Procainamide is the preferred initial drug in stable pre-excited AF with WPW (lecture): it prolongs refractoriness of the Na⁺-dependent accessory pathway itself. How much depends on that pathway’s own baseline refractory period — short-ERP (high-risk) pathways respond least, which is why procainamide is also used as a diagnostic test.']);
      if (base === 'preaf' && drug === 'amiodarone') W.push(['warn', '2024 ESC guidance: avoid amiodarone in pre-excited AF — its action is delayed and it has AV-nodal blocking effects. Not a lecture statement.']);
      if (drug === 'flecainide' && base === 'nsr') W.push(['warn', 'Watch the QRS: flecainide is the archetypal QRS-widener. Contraindicated after MI and in significant structural heart disease (lecture) — marked conduction slowing in scarred myocardium is pro-arrhythmic.']);
      if ((drug === 'sotalol' || drug === 'amiodarone' || drug === 'procainamide') && Ko < 3.4) W.push(['danger', 'QT-prolonging drug plus hypokalaemia. Low [K⁺]o reduces I_Kr AND deepens the drug’s block of it — the classic setting for torsades de pointes. Check the action-potential lab for the early after-depolarisation.']);
      if (drug === 'digoxin' && Ko < 3.4) W.push(['danger', 'Hypokalaemia increases digoxin toxicity: K⁺ normally competes with digoxin at the Na⁺/K⁺-ATPase, so less K⁺ means more binding (Q23).']);
      if (base === 'af' && ['verapamil', 'diltiazem', 'metoprolol', 'digoxin'].includes(drug)) W.push(['good', 'Rate control: the AV-nodal ERP lengthens, so fewer fibrillatory impulses reach the ventricles. The rhythm stays irregularly irregular — rate control does not restore sinus rhythm.']);
      if (base === 'af' && drug === 'lidocaine') W.push(['warn', 'Lidocaine has no AV-nodal effect and no role in AF — the trace is essentially unchanged. It is a ventricular drug.']);
      W.forEach((w) => expl.appendChild(h('div', { class: 'ctx ctx-' + w[0] }, h('b', {}, w[0] === 'danger' ? '⚠ Contraindicated / dangerous' : w[0] === 'warn' ? '⚠ Caution' : '✓ Appropriate'), h('span', {}, w[1]))));
      expl.appendChild(U.note('M', 'Both traces are model output. Interval changes show direction and relative size; they are not patient predictions, and the model has no dose–response.'));
    }
    const fmt = (v) => isFinite(v) ? Math.round(v) + ' ms' : 'block';
    if (sub === 'preaf') { base = 'preaf'; baseSeg.setCur('preaf'); drug = 'procainamide'; }
    else if (sub && K.drugs[sub]) drug = sub;
    draw();
    const c = U.checks('drugecg'); if (c) m.appendChild(c);
    m.appendChild(U.kp(['Na⁺ blockers widen the QRS; K⁺ blockers lengthen the QT; AV-nodal blockers lengthen the PR and slow the rate.', 'The same drug can be right in one rhythm and lethal in another — verapamil in AF versus verapamil in VT.', 'In pre-excited AF the accessory pathway, not the AV node, sets the ventricular rate.', 'Electrolytes change drug effects: hypokalaemia amplifies I_Kr block and digoxin binding.']));
  };
